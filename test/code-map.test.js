import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { MAP_FILE, renderMap } from "../src/code-map.js";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const COMMITTED_MAP = path.join(ROOT, MAP_FILE);

function fixture() {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "po-shell-code-map-"));
  const write = (rel, body) => {
    const file = path.join(dir, rel);
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, body);
  };
  write("src/a.js", "export function alpha() {}\nexport const beta = 1;\n");
  write("src/b.js", 'import { alpha, beta } from "./a.js";\n\nexport function combined() {\n  return alpha() + beta;\n}\n');
  write("src/c.js", "const lonely = 1;\n");
  write("node_modules/big/index.js", "export const hidden = 1;\n");
  return dir;
}

function cliFixture() {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "po-shell-code-map-cli-"));
  fs.mkdirSync(path.join(dir, "src"), { recursive: true });
  fs.writeFileSync(path.join(dir, "src", "a.js"), "export function alpha() {}\n");
  return dir;
}

/** Runs `po-shell <args>` from `cwd`, the way the bin does. */
function runCli(args, cwd) {
  return spawnSync(process.execPath, [path.join(ROOT, "bin", "po-shell.js"), ...args], {
    cwd,
    encoding: "utf8",
  });
}

test("the map lists exports and, for each importer, the names it imports", () => {
  const expected = [
    "---",
    "type: map",
    "generated: true",
    "---",
    "",
    "# code map · 3 files · 1 import edges",
    "",
    "Generated by `npm run code:map`; checked by `npm test`. Do not edit by hand.",
    "",
    "## src/a.js",
    "",
    "- exports: alpha, beta",
    "- imported by: src/b.js (alpha, beta)",
    "",
    "## src/b.js",
    "",
    "- exports: combined",
    "",
  ].join("\n");

  const map = renderMap(fixture());
  assert.equal(map, expected);
});

test("scripts/code-map.mjs is a thin CLI over src/code-map.js", () => {
  const dir = fixture();
  const script = path.join(ROOT, "scripts", "code-map.mjs");

  const printed = spawnSync(process.execPath, [script, dir], { encoding: "utf8" });
  assert.equal(printed.status, 0, printed.stderr);
  assert.equal(printed.stdout, renderMap(dir), "stdout is the map for the root argument");

  const missing = spawnSync(process.execPath, [script, "--check", dir], { encoding: "utf8" });
  assert.equal(missing.status, 1);
  assert.match(missing.stderr, /is missing/);

  fs.mkdirSync(path.join(dir, "docs"), { recursive: true });
  fs.writeFileSync(path.join(dir, MAP_FILE), printed.stdout);
  const fresh = spawnSync(process.execPath, [script, "--check", dir], { encoding: "utf8" });
  assert.equal(fresh.status, 0, fresh.stderr);

  fs.writeFileSync(path.join(dir, MAP_FILE), "stale\n");
  const stale = spawnSync(process.execPath, [script, "--check", dir], { encoding: "utf8" });
  assert.equal(stale.status, 1);
  assert.match(stale.stderr, /is stale/);
});

test("po-shell map writes docs/code-map.md and prints one line", () => {
  const dir = cliFixture();
  const run = runCli(["map"], dir);
  assert.equal(run.status, 0, run.stderr);
  assert.equal(run.stdout.trim(), "mapa: docs/code-map.md · 1 archivos · 0 aristas");

  const written = fs.readFileSync(path.join(dir, MAP_FILE), "utf8");
  assert.equal(written, renderMap(dir), "the command writes the same map renderMap returns");
});

test("po-shell map --check passes when fresh and names the first difference when stale", () => {
  const dir = cliFixture();
  assert.equal(runCli(["map"], dir).status, 0);

  const fresh = runCli(["map", "--check"], dir);
  assert.equal(fresh.status, 0, fresh.stderr);
  assert.match(fresh.stdout, /mapa al día/);

  const file = path.join(dir, MAP_FILE);
  fs.writeFileSync(file, fs.readFileSync(file, "utf8").replace("type: map", "type: stale"));
  const stale = runCli(["map", "--check"], dir);
  assert.equal(stale.status, 1);
  assert.match(stale.stderr, /docs\/code-map\.md:2 está desactualizado/);
  assert.match(stale.stderr, /esperado:/);

  fs.rmSync(file);
  const missing = runCli(["map", "--check"], dir);
  assert.equal(missing.status, 1);
  assert.match(missing.stderr, /no existe/);
});

test("po-shell map --json reports the same counts", () => {
  const dir = cliFixture();
  const run = runCli(["map", "--json"], dir);
  assert.equal(run.status, 0, run.stderr);
  const payload = JSON.parse(run.stdout);
  assert.deepEqual(payload, { path: "docs/code-map.md", files: 1, edges: 0, written: true });
});

test(
  "the committed docs/code-map.md matches renderMap of the repo",
  {
    skip: fs.existsSync(COMMITTED_MAP)
      ? false
      : "docs/code-map.md no existe todavía; generálo con po-shell map",
  },
  () => {
    const committed = fs.readFileSync(COMMITTED_MAP, "utf8");
    assert.equal(committed, renderMap(ROOT), "docs/code-map.md is stale; run po-shell map");

    const over = committed.split("\n").find((line) => line.length > 100);
    assert.equal(over, undefined, `the map has a line over 100 characters: ${over?.slice(0, 40)}…`);
  },
);
